def make_polygon(lat, lng, area_ha):
    import math
    side = math.sqrt(area_ha * 10000)  # метры
    dlat = side / 2 / 111000
    dlng = side / 2 / (111000 * math.cos(math.radians(lat)))
    return [[lat - dlat, lng - dlng * 1.2], [lat - dlat * 0.7, lng + dlng], [lat + dlat, lng + dlng * 0.8],
            [lat + dlat * 0.9, lng - dlng], [lat - dlat, lng - dlng * 1.2]]


